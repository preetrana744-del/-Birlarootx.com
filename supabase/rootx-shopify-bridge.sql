-- Birla RootX: dormant Shopify bridge. Existing order-request checkout remains valid.
-- Apply only after review. The caller must verify Shopify HMAC and shop domain
-- before invoking rootx_ingest_shopify_order with a normalized order snapshot.

alter table public.rootx_orders
  add column if not exists source text not null default 'request'
    check (source in ('request','shopify')),
  add column if not exists shopify_order_id text unique
    check (shopify_order_id is null or shopify_order_id ~ '^[0-9]{1,30}$'),
  add column if not exists shopify_updated_at timestamptz,
  add column if not exists payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid','pending','authorized','partially_paid','paid',
      'partially_refunded','refunded','voided')),
  add column if not exists total numeric(12,2)
    check (total is null or (total >= 0 and total <= 1000000)),
  add column if not exists currency text not null default 'INR'
    check (currency ~ '^[A-Z]{3}$');

-- Shopify may legitimately record a fully discounted order or no shipping phone.
-- The existing request RPC still requires its phone and positive catalog prices.
alter table public.rootx_orders drop constraint if exists rootx_orders_shipping_phone_check;
alter table public.rootx_orders add constraint rootx_orders_shipping_phone_check
  check (shipping_phone ~ '^\+?[0-9]{7,15}$' or (source='shopify' and shipping_phone=''));
alter table public.rootx_orders drop constraint if exists rootx_orders_subtotal_check;
alter table public.rootx_orders add constraint rootx_orders_subtotal_check
  check (subtotal <= 1000000 and (subtotal > 0 or (source='shopify' and subtotal=0)));
alter table public.rootx_order_items drop constraint if exists rootx_order_items_unit_price_check;
alter table public.rootx_order_items add constraint rootx_order_items_unit_price_check
  check (unit_price >= 0 and unit_price <= 1000000);

create table if not exists public.rootx_shopify_variants (
  slug text primary key references public.rootx_products(slug),
  product_id text not null unique
    check (product_id ~ '^(gid://shopify/Product/)?[0-9]{1,30}$'),
  variant_id text not null unique
    check (variant_id ~ '^(gid://shopify/ProductVariant/)?[0-9]{1,30}$')
);

create unique index if not exists rootx_shopify_variants_canonical_variant_idx
  on public.rootx_shopify_variants ((regexp_replace(variant_id,'^gid://shopify/ProductVariant/','')));
create unique index if not exists rootx_shopify_variants_canonical_product_idx
  on public.rootx_shopify_variants ((regexp_replace(product_id,'^gid://shopify/Product/','')));

create table if not exists public.rootx_shopify_checkouts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  client_request_id uuid not null,
  -- Canonical [{variant_id, quantity}], generated by the server, never prices/PII.
  items jsonb not null check (jsonb_typeof(items) = 'array'
    and jsonb_array_length(items) between 1 and 50),
  cart_id text check (cart_id is null or length(cart_id) between 1 and 2048),
  checkout_url text check (checkout_url is null or (length(checkout_url) <= 4096
    and checkout_url ~ '^https://')),
  -- Only a SHA-256 digest is retained; the original random proof stays in Shopify.
  link_token_hash text not null unique check (link_token_hash ~ '^[a-f0-9]{64}$'),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '7 days'),
  consumed_order_id text check (consumed_order_id is null
    or consumed_order_id ~ '^[0-9]{1,30}$'),
  unique (user_id, client_request_id),
  check (expires_at > created_at)
);
create index if not exists rootx_shopify_checkouts_user_created_idx
  on public.rootx_shopify_checkouts(user_id,created_at desc);
create index if not exists rootx_shopify_checkouts_expiry_idx
  on public.rootx_shopify_checkouts(expires_at) where consumed_order_id is null;

create table if not exists public.rootx_shopify_webhook_events (
  event_id text primary key check (length(event_id) between 1 and 200),
  received_at timestamptz not null default now()
);
create index if not exists rootx_shopify_webhook_events_received_idx
  on public.rootx_shopify_webhook_events(received_at);

-- These integration tables have no browser policies. Only trusted server code
-- using service_role can read/write; customers still use existing order RLS.
alter table public.rootx_shopify_variants enable row level security;
alter table public.rootx_shopify_checkouts enable row level security;
alter table public.rootx_shopify_webhook_events enable row level security;
revoke all on public.rootx_shopify_variants, public.rootx_shopify_checkouts,
  public.rootx_shopify_webhook_events from public, anon, authenticated;
grant all on public.rootx_shopify_variants, public.rootx_shopify_checkouts,
  public.rootx_shopify_webhook_events to service_role;

-- Reserve idempotency and the hourly allowance in one per-customer transaction.
create or replace function public.rootx_reserve_shopify_checkout(payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id uuid;
  v_user uuid;
  v_request uuid;
  v_expires timestamptz;
  v_row public.rootx_shopify_checkouts%rowtype;
  v_item jsonb;
begin
  if jsonb_typeof(payload) is distinct from 'object'
    or coalesce(payload->>'id','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    or coalesce(payload->>'user_id','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    or coalesce(payload->>'client_request_id','') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    or coalesce(payload->>'link_token_hash','') !~ '^[a-f0-9]{64}$'
    or jsonb_typeof(payload->'items') is distinct from 'array'
    or jsonb_array_length(payload->'items') not between 1 and 20 then
    raise exception using errcode='22023', message='Invalid checkout reservation';
  end if;
  v_id := (payload->>'id')::uuid;
  v_user := (payload->>'user_id')::uuid;
  v_request := (payload->>'client_request_id')::uuid;
  v_expires := (payload->>'expires_at')::timestamptz;
  if v_expires is null or v_expires <= now() or v_expires > now()+interval '7 days' then
    raise exception using errcode='22023', message='Invalid checkout expiry';
  end if;
  for v_item in select value from jsonb_array_elements(payload->'items') loop
    if jsonb_typeof(v_item) is distinct from 'object'
      or coalesce(v_item->>'variant_id','') !~ '^(gid://shopify/ProductVariant/)?[0-9]{1,30}$'
      or coalesce(v_item->>'quantity','') !~ '^[0-9]{1,2}$'
      or (v_item->>'quantity')::integer not between 1 and 99 then
      raise exception using errcode='22023', message='Invalid checkout items';
    end if;
  end loop;
  perform pg_advisory_xact_lock(hashtextextended(v_user::text,0));
  select * into v_row from public.rootx_shopify_checkouts
    where user_id=v_user and client_request_id=v_request;
  if found then
    return jsonb_build_object('created',false,'checkout',to_jsonb(v_row));
  end if;
  if (select count(*) from public.rootx_shopify_checkouts
    where user_id=v_user and created_at >= now()-interval '1 hour') >= 10 then
    raise exception using errcode='P0001', message='Checkout rate limit reached';
  end if;
  insert into public.rootx_shopify_checkouts(id,user_id,client_request_id,items,
    link_token_hash,expires_at)
    values (v_id,v_user,v_request,payload->'items',payload->>'link_token_hash',v_expires)
    returning * into v_row;
  return jsonb_build_object('created',true,'checkout',to_jsonb(v_row));
end;
$$;
revoke all on function public.rootx_reserve_shopify_checkout(jsonb) from public, anon, authenticated;
grant execute on function public.rootx_reserve_shopify_checkout(jsonb) to service_role;

create or replace function public.rootx_ingest_shopify_order(payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_checkout public.rootx_shopify_checkouts%rowtype;
  v_order public.rootx_orders%rowtype;
  v_order_id uuid;
  v_event_id text := payload->>'event_id';
  v_shopify_id text := payload->>'shopify_order_id';
  v_token_hash text := payload->>'token_hash';
  v_cart_token text := payload->>'cart_token';
  v_remote_updated timestamptz;
  v_payment text := coalesce(nullif(payload->>'payment_status',''),'unpaid');
  v_currency text := payload->>'currency';
  v_subtotal numeric;
  v_total numeric;
  v_items jsonb;
  v_proof_items jsonb;
  v_item jsonb;
  v_slug text;
  v_name text;
  v_image text;
  v_quantity integer;
  v_unit_price numeric;
  v_status text;
  v_is_new boolean;
  v_inserted integer;
  v_tracking text;
  v_courier text;
  v_incoming_rank integer;
  v_existing_rank integer;
begin
  if jsonb_typeof(payload) is distinct from 'object'
    or coalesce(length(v_event_id),0) not between 1 and 200
    or v_shopify_id is null or v_shopify_id !~ '^[0-9]{1,30}$' then
    raise exception using errcode = '22023', message = 'Invalid Shopify event identity';
  end if;

  -- The receipt, proof consumption, order and items are committed together.
  -- A failed import rolls back its receipt so Shopify can retry safely.
  insert into public.rootx_shopify_webhook_events(event_id)
    values (v_event_id) on conflict (event_id) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    return jsonb_build_object('duplicate',true);
  end if;

  if v_token_hash is null or v_token_hash !~ '^[a-f0-9]{64}$'
    or coalesce(length(v_cart_token),0) not between 1 and 1024 then
    return jsonb_build_object('ignored',true,'reason','unlinked_order');
  end if;
  select * into v_checkout from public.rootx_shopify_checkouts
    where link_token_hash = v_token_hash for update;
  if not found or v_checkout.cart_id is null or
    split_part(regexp_replace(v_checkout.cart_id,'^gid://shopify/Cart/',''), '?', 1)
      <> v_cart_token then
    return jsonb_build_object('ignored',true,'reason','unlinked_order');
  end if;
  if v_checkout.consumed_order_id is not null
    and v_checkout.consumed_order_id <> v_shopify_id then
    raise exception using errcode = '22023', message = 'Checkout proof already belongs to another order';
  end if;
  if v_checkout.consumed_order_id is null and v_checkout.expires_at <= now() then
    return jsonb_build_object('ignored',true,'reason','expired_checkout');
  end if;

  select * into v_order from public.rootx_orders
    where shopify_order_id = v_shopify_id for update;
  v_is_new := not found;
  if not v_is_new and (v_order.source <> 'shopify'
    or v_order.customer_id is distinct from v_checkout.user_id) then
    raise exception using errcode = '22023', message = 'Shopify order ownership mismatch';
  end if;
  v_remote_updated := (payload->>'updated_at')::timestamptz;
  if v_remote_updated is null then
    raise exception using errcode = '22023', message = 'Missing Shopify update timestamp';
  end if;
  -- Shopify can deliver topics out of order. Older snapshots never apply.
  if not v_is_new and v_order.shopify_updated_at is not null
    and v_remote_updated < v_order.shopify_updated_at then
    return jsonb_build_object('stale',true,'order_id',v_order.id);
  end if;

  if v_payment not in ('unpaid','pending','authorized','partially_paid','paid',
    'partially_refunded','refunded','voided') then
    raise exception using errcode = '22023', message = 'Unsupported Shopify payment status';
  end if;
  -- Several Shopify topics can share second-resolution updated_at. Reconcile
  -- monotonic payment/dispatch changes without replacing competing snapshots.
  if not v_is_new and v_remote_updated = v_order.shopify_updated_at then
    v_incoming_rank := array_position(array['unpaid','pending','authorized','partially_paid',
      'paid','partially_refunded','refunded'],v_payment);
    v_existing_rank := array_position(array['unpaid','pending','authorized','partially_paid',
      'paid','partially_refunded','refunded'],v_order.payment_status);
    if v_order.payment_status = 'voided' then
      v_payment := 'voided';
    elsif v_payment = 'voided' then
      v_payment := case when v_order.payment_status in ('unpaid','pending','authorized')
        then 'voided' else v_order.payment_status end;
    elsif v_incoming_rank <= v_existing_rank then
      v_payment := v_order.payment_status;
    end if;
    v_status := v_order.status;
    if coalesce((payload->>'cancelled')::boolean,false) then
      v_status := 'cancelled';
    elsif v_status not in ('cancelled','out_for_delivery','delivered') then
      if payload->>'fulfillment_status' = 'fulfilled' then
        v_status := 'shipped';
      elsif v_status = 'received' and v_payment in ('paid','partially_refunded','refunded') then
        v_status := 'confirmed';
      end if;
    end if;
    -- Fill tracking that has not yet arrived; same-second competing data cannot
    -- replace a tracking number or courier already saved by the administrator.
    v_tracking := coalesce(nullif(v_order.tracking_number,''),
      left(coalesce(btrim(payload->>'tracking_number'),''),100));
    v_courier := coalesce(nullif(v_order.courier,''),
      left(coalesce(btrim(payload->>'courier'),''),100));
    if (v_payment,v_status,v_tracking,v_courier) is not distinct from
      (v_order.payment_status,v_order.status,v_order.tracking_number,v_order.courier) then
      return jsonb_build_object('stale',true,'order_id',v_order.id);
    end if;
    update public.rootx_orders set payment_status=v_payment,status=v_status,
      tracking_number=v_tracking,courier=v_courier where id=v_order.id;
    return jsonb_build_object('order_id',v_order.id,'created',false,'reconciled',true);
  end if;

  -- The current storefront displays INR. Do not mislabel a foreign-currency order.
  if v_currency is distinct from 'INR' then
    raise exception using errcode = '22023', message = 'Unsupported Shopify order currency';
  end if;
  v_subtotal := (payload->>'subtotal')::numeric;
  v_total := (payload->>'total')::numeric;
  if v_subtotal is null or v_subtotal < 0 or v_subtotal > 1000000
    or v_total is null or v_total < 0 or v_total > 1000000 then
    raise exception using errcode = '22023', message = 'Unsupported Shopify order amount';
  end if;
  if coalesce(length(btrim(payload->>'shipping_name')),0) not between 2 and 120
    or (coalesce(payload->>'shipping_phone','') <> ''
      and payload->>'shipping_phone' !~ '^\+?[0-9]{7,15}$')
    or coalesce(length(btrim(payload->>'shipping_address')),0) not between 10 and 1000 then
    raise exception using errcode = '22023', message = 'Missing or invalid Shopify shipping details';
  end if;
  if jsonb_typeof(payload->'items') is distinct from 'array'
    or jsonb_array_length(payload->'items') not between 1 and 50 then
    raise exception using errcode = '22023', message = 'Invalid Shopify order items';
  end if;

  -- Normalize numeric variant IDs and GIDs to the same representation.
  -- Require one distinct variant per product; that matches the existing cart.
  for v_item in select value from jsonb_array_elements(payload->'items') loop
    if jsonb_typeof(v_item) is distinct from 'object'
      or coalesce(v_item->>'variant_id','') !~ '^(gid://shopify/ProductVariant/)?[0-9]{1,30}$'
      or coalesce(v_item->>'quantity','') !~ '^[0-9]{1,2}$' then
      raise exception using errcode = '22023', message = 'Invalid Shopify order item';
    end if;
    v_quantity := (v_item->>'quantity')::integer;
    v_unit_price := (v_item->>'unit_price')::numeric;
    if v_quantity not between 1 and 99 or v_unit_price is null
      or v_unit_price < 0 or v_unit_price > 1000000 then
      raise exception using errcode = '22023', message = 'Unsupported Shopify line amount or quantity';
    end if;
    select m.slug, p.name, p.image_url into v_slug,v_name,v_image
      from public.rootx_shopify_variants m join public.rootx_products p on p.slug=m.slug
      where regexp_replace(m.variant_id,'^gid://shopify/ProductVariant/','') =
        regexp_replace(v_item->>'variant_id','^gid://shopify/ProductVariant/','');
    if not found then
      raise exception using errcode = '22023', message = 'Unmapped Shopify variant';
    end if;
  end loop;
  if (select count(*) from jsonb_array_elements(payload->'items')) <>
    (select count(distinct regexp_replace(value->>'variant_id',
      '^gid://shopify/ProductVariant/','')) from jsonb_array_elements(payload->'items')) then
    raise exception using errcode = '22023', message = 'Duplicate Shopify variant';
  end if;

  select jsonb_agg(jsonb_build_object('variant_id',
      regexp_replace(value->>'variant_id','^gid://shopify/ProductVariant/',''),
      'quantity',(value->>'quantity')::integer)
      order by regexp_replace(value->>'variant_id','^gid://shopify/ProductVariant/',''))
    into v_items from jsonb_array_elements(payload->'items');
  select jsonb_agg(jsonb_build_object('variant_id',
      regexp_replace(value->>'variant_id','^gid://shopify/ProductVariant/',''),
      'quantity',(value->>'quantity')::integer)
      order by regexp_replace(value->>'variant_id','^gid://shopify/ProductVariant/',''))
    into v_proof_items from jsonb_array_elements(v_checkout.items);
  if v_is_new and v_items is distinct from v_proof_items then
    raise exception using errcode = '22023', message = 'Checkout contents do not match order';
  end if;

  -- A fulfillment marks dispatch, never delivery. Later manual delivery states
  -- are preserved until Shopify explicitly cancels the order.
  if coalesce((payload->>'cancelled')::boolean,false) then
    v_status := 'cancelled';
  elsif not v_is_new and v_order.status in ('cancelled','out_for_delivery','delivered') then
    v_status := v_order.status;
  elsif payload->>'fulfillment_status' = 'fulfilled' then
    v_status := 'shipped';
  elsif not v_is_new and v_order.status in ('packed','shipped') then
    v_status := v_order.status;
  elsif v_payment in ('paid','partially_refunded','refunded') then
    v_status := 'confirmed';
  else
    v_status := case when v_is_new then 'received' else v_order.status end;
  end if;

  if v_is_new then
    if exists (select 1 from public.rootx_orders where customer_id=v_checkout.user_id
      and client_request_id=v_checkout.client_request_id) then
      raise exception using errcode = '22023', message = 'Checkout request already used';
    end if;
    insert into public.rootx_orders(
      order_number,customer_id,status,shipping_name,shipping_phone,shipping_address,
      subtotal,client_request_id,checkout_payload,source,shopify_order_id,
      shopify_updated_at,payment_status,total,currency,courier,tracking_number)
    values (
      'S-' || left(coalesce(nullif(btrim(payload->>'order_number'),''),v_shopify_id),100),
      v_checkout.user_id,v_status,btrim(payload->>'shipping_name'),
      coalesce(payload->>'shipping_phone',''),btrim(payload->>'shipping_address'),
      v_subtotal,v_checkout.client_request_id,
      jsonb_build_object('source','shopify','shopify_order_id',v_shopify_id,'items',v_items),
      'shopify',v_shopify_id,v_remote_updated,v_payment,v_total,v_currency,
      left(coalesce(payload->>'courier',''),100),left(coalesce(payload->>'tracking_number',''),100))
    returning id into v_order_id;
  else
    v_order_id := v_order.id;
    update public.rootx_orders set
      status=v_status,shipping_name=btrim(payload->>'shipping_name'),
      shipping_phone=coalesce(payload->>'shipping_phone',''),shipping_address=btrim(payload->>'shipping_address'),
      subtotal=v_subtotal,total=v_total,currency=v_currency,payment_status=v_payment,
      shopify_updated_at=v_remote_updated,
      courier=coalesce(nullif(left(btrim(payload->>'courier'),100),''),courier),
      tracking_number=coalesce(nullif(left(btrim(payload->>'tracking_number'),100),''),tracking_number)
      where id=v_order_id;
  end if;

  -- Store only known catalog variants; never use a webhook's slug/image as a FK.
  -- Keep the original catalog photo on later payment/fulfillment webhooks.
  -- A legitimate Shopify order edit can update quantities/prices or remove lines.
  insert into public.rootx_order_items(order_id,product_slug,product_name,quantity,unit_price,image_url)
    select v_order_id,m.slug,
      left(coalesce(nullif(btrim(line.value->>'name'),''),p.name),120),
      (line.value->>'quantity')::integer,(line.value->>'unit_price')::numeric,p.image_url
    from jsonb_array_elements(payload->'items') line
    join public.rootx_shopify_variants m on regexp_replace(m.variant_id,
      '^gid://shopify/ProductVariant/','')=regexp_replace(line.value->>'variant_id',
      '^gid://shopify/ProductVariant/','')
    join public.rootx_products p on p.slug=m.slug
    where true
    on conflict (order_id,product_slug) do update set
      product_name=excluded.product_name,quantity=excluded.quantity,unit_price=excluded.unit_price;
  delete from public.rootx_order_items oi where oi.order_id=v_order_id
    and not exists (select 1 from jsonb_array_elements(payload->'items') line
      join public.rootx_shopify_variants m on regexp_replace(m.variant_id,
        '^gid://shopify/ProductVariant/','')=regexp_replace(line.value->>'variant_id',
        '^gid://shopify/ProductVariant/','') where m.slug=oi.product_slug);

  update public.rootx_shopify_checkouts set consumed_order_id=v_shopify_id
    where id=v_checkout.id;
  return jsonb_build_object('order_id',v_order_id,'created',v_is_new);
end;
$$;
revoke all on function public.rootx_ingest_shopify_order(jsonb) from public, anon, authenticated;
grant execute on function public.rootx_ingest_shopify_order(jsonb) to service_role;
comment on function public.rootx_ingest_shopify_order(jsonb) is
  'Service-only transactional import of an HMAC-verified Shopify order. Customer ownership requires a stored random checkout proof and matching cart token; email is never an identity key.';
